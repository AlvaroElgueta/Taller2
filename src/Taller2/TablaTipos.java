	public static int getIndiceTipo(String tipo) {
		for (int i = 0; i < TIPOS.length; i++) {
			if (TIPOS[i].equalsIgnoreCase(tipo)) {
				return i;
			}
		}

		return -1;
	}

	public static double getEfectividad(String tipoJugador, String tipoRival) {
		int fila = getIndiceTipo(tipoJugador);
		int columna = getIndiceTipo(tipoRival);

		if (fila == -1 || columna == -1) {
			return 1.0;
		}

		return EFECTIVIDAD[fila][columna];
	}
